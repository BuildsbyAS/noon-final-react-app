/**
 * One drawing, no crossfade — for the calling card's resting pill (filled) and
 * the panel's answer pills (outline), where the variant is fixed by context.
 */
export function StaticGlyph({
  glyph,
  variant,
  size,
  ink,
  knockout = "#ffffff",
}: {
  glyph: V14GlyphId;
  variant: "outline" | "filled";
  size: number;
  ink: string;
  knockout?: string;
}) {
  return <RawGlyph drawing={GLYPH[glyph][variant]} size={size} ink={ink} knockout={knockout} />;
}

export function OptionGlyph({
  glyph,
  size,
  selected,
  playKey,
  reduceMotion,
}: {
  glyph: V14GlyphId;
  size: number;
  selected: boolean;
  /** Bumped on every tap, including a tap on the already-selected answer. */
  playKey: number;
  reduceMotion: boolean;
}) {
  const controls = useAnimationControls();
  const sig = SIGNATURE[glyph];
  const { outline, filled } = GLYPH[glyph];

  useEffect(() => {
    if (playKey === 0 || reduceMotion) return;
    // set-then-start: a keyframe array has to replay from a known pose.
    controls.set(sig.from);
    void controls.start(sig.to);
  }, [playKey, reduceMotion, controls, sig]);

  return (
    <motion.span
      aria-hidden="true"
      className="relative block shrink-0"
      style={{
        width: size,
        height: size,
        transformOrigin: sig.origin,
        transformPerspective: 150,
      }}
      animate={controls}
    >
      <motion.span
        className="absolute inset-0 block"
        initial={false}
        animate={{ opacity: selected ? 0 : 1 }}
        transition={reduceMotion ? { duration: 0 } : FADE}
      >
        <RawGlyph
          drawing={outline}
          size={size}
          ink={INK_MUTED}
          knockout={SURFACE_TRACK}
        />
      </motion.span>
      <motion.span
        className="absolute inset-0 block"
        initial={false}
        animate={{ opacity: selected ? 1 : 0 }}
        transition={reduceMotion ? { duration: 0 } : FADE}
      >
        <RawGlyph
          drawing={filled}
          size={size}
          ink={INK_PRIMARY}
          knockout={SURFACE_THUMB}
        />
      </motion.span>
    </motion.span>
  );
}
