function RawGlyph({
  drawing,
  size,
  ink,
  knockout,
}: { drawing: Drawing; size: number } & Parts) {
  return (
    <svg
      width={size}
      height={size}
      viewBox={drawing.viewBox}
      fill="none"
      aria-hidden="true"
      focusable="false"
      className="block shrink-0"
    >
      {drawing.draw({ ink, knockout })}
    </svg>
  );
}

